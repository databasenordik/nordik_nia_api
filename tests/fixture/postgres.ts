import { PGlite } from "@electric-sql/pglite"
import { PGLiteSocketServer } from "@electric-sql/pglite-socket"
import { SQL } from "bun"

// The conversation tables as nordik_nia_api's migrations 004, 023 and 074 leave them, in an in-process
// PostgreSQL. assistant_api.potential_access_revision() returns whatever the test last stored.
export const conversationSchema = `
CREATE SCHEMA assistant;
CREATE SCHEMA assistant_api;
CREATE TABLE assistant.conversations (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  principal_id TEXT NOT NULL,
  title TEXT,
  current_mode TEXT NOT NULL DEFAULT 'text',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  selected_file_id INTEGER,
  user_id BIGINT,
  file_id INTEGER GENERATED ALWAYS AS (selected_file_id) STORED
);
CREATE UNIQUE INDEX idx_conversations_user_file ON assistant.conversations (user_id, file_id) WHERE user_id IS NOT NULL;
CREATE TABLE assistant.messages (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  conversation_id UUID NOT NULL REFERENCES assistant.conversations(id) ON DELETE CASCADE,
  turn_id TEXT NOT NULL,
  role TEXT NOT NULL,
  text TEXT,
  mode TEXT NOT NULL DEFAULT 'text',
  interrupted BOOLEAN NOT NULL DEFAULT FALSE,
  delivered_text_boundary INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  exchange_id UUID NOT NULL,
  communities TEXT[] NOT NULL DEFAULT '{}',
  row_access_revision TEXT
);
CREATE UNIQUE INDEX idx_messages_exchange_role ON assistant.messages (conversation_id, exchange_id, role);
CREATE TABLE assistant.conversation_state (
  conversation_id UUID PRIMARY KEY REFERENCES assistant.conversations(id) ON DELETE CASCADE,
  rolling_summary TEXT,
  active_entities JSONB NOT NULL DEFAULT '{}'::jsonb,
  active_dataset_scope JSONB NOT NULL DEFAULT '{}'::jsonb,
  active_query_state JSONB NOT NULL DEFAULT '{}'::jsonb,
  last_source_ids TEXT[] NOT NULL DEFAULT '{}',
  pending_references JSONB NOT NULL DEFAULT '{}'::jsonb,
  state_version INTEGER NOT NULL DEFAULT 1,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE assistant.audit_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  principal_id TEXT,
  event_type TEXT NOT NULL,
  conversation_id UUID,
  query_run_id UUID,
  dataset_ids INTEGER[] NOT NULL DEFAULT '{}',
  authorization_outcome TEXT,
  provider_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE assistant_api.release (revision TEXT);
INSERT INTO assistant_api.release VALUES ('release-1');
CREATE FUNCTION assistant_api.potential_access_revision() RETURNS TEXT
  LANGUAGE sql STABLE AS $$ SELECT revision FROM assistant_api.release $$;
`

export async function postgres(schema = conversationSchema) {
  const db = await PGlite.create()
  await db.exec(schema)
  // PGlite is one session, and the socket server interleaves connections statement by statement, so
  // two connections are only safe while they are not used at the same time: the code under test and
  // this fixture each get one, and tests query the fixture only once the code under test is idle.
  const server = new PGLiteSocketServer({ db, host: "127.0.0.1", port: 0, maxConnections: 2 })
  await server.start()
  const address = (server as unknown as { server: { address(): { port: number } } }).server.address()
  const url = `postgres://postgres:postgres@127.0.0.1:${address.port}/postgres`
  const sql = new SQL({ url, max: 1, ssl: "disable" })
  return {
    url,
    sql,
    reset: () => sql`TRUNCATE assistant.conversations, assistant.audit_events CASCADE`,
    release: (revision: string) => sql`UPDATE assistant_api.release SET revision = ${revision}`,
    [Symbol.asyncDispose]: async () => {
      await sql.close()
      await server.stop()
      await db.close()
    },
  }
}
